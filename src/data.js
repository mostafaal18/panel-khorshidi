/* ── توابع کمکی درخت دسته‌بندی ── */
export const getCategoryBySlug = (slug) =>
  categories.find((c) => c.slug === slug) || null

export const getTopCategories = () => categories.filter((c) => !c.parent)

export const getSubcategories = (parentSlug) =>
  categories.filter((c) => c.parent === parentSlug)

export const getDescendants = (slug) => {
  const out = [slug]
  const walk = (s) => {
    categories.filter((c) => c.parent === s).forEach((c) => {
      out.push(c.slug)
      walk(c.slug)
    })
  }
  walk(slug)
  return out
}

export const getAncestors = (slug) => {
  const out = []
  let cur = getCategoryBySlug(slug)
  while (cur?.parent) {
    const p = getCategoryBySlug(cur.parent)
    if (p) out.unshift(p)
    cur = p
  }
  return out
}